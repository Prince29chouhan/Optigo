def evaluate_route(vehicle: Vehicle, stops: List[Stop], provider: DistanceProvider,
                   options: PlanOptions) -> dict:
    """Walk a stop sequence and produce a fully costed, validated itinerary."""
    profile = vehicle.cost_profile()

    legs: List[dict] = []
    timeline: List[dict] = []
    violations: List[dict] = []

    load_kg = 0.0
    load_m3 = 0.0
    load_pallets = 0
    # Delivery-only orders are loaded at the start depot, so the vehicle leaves
    # base already carrying them.
    for stop in stops:
        if stop.type == 'delivery' and stop.weight_kg < 0 and not _has_matching_pickup(stops, stop):
            load_kg += -stop.weight_kg
            load_m3 += -stop.volume_m3
            load_pallets += stop.pallets

    start_load_kg = load_kg
    peak_load_kg = load_kg
    peak_load_m3 = load_m3

    if options.enforce_capacity and _over_capacity(vehicle, load_kg, load_m3, load_pallets):
        return _infeasible(vehicle, 'Start load exceeds vehicle capacity')

    clock = float(vehicle.shift_start_min)
    driving_since_break = 0.0
    totals = {
        'distance_km': 0.0, 'empty_km': 0.0, 'loaded_km': 0.0,
        'driving_minutes': 0.0, 'service_minutes': 0.0, 'waiting_minutes': 0.0,
        'break_minutes': 0.0, 'energy': 0.0, 'co2_kg': 0.0,
        'fuel_cost_gbp': 0.0, 'running_cost_gbp': 0.0, 'driver_cost_gbp': 0.0,
    }

    timeline.append({
        'sequence': 0, 'type': 'depot_start', 'name': vehicle.start.name,
        'lat': vehicle.start.lat, 'lon': vehicle.start.lon,
        'location_id': vehicle.start.location_id,
        'arrival': minutes_to_hhmm(clock), 'departure': minutes_to_hhmm(clock),
        'load_kg': round(load_kg, 2), 'load_m3': round(load_m3, 3),
        'service_minutes': 0, 'order_id': None, 'order_ref': None, 'auto': False,
        'address': vehicle.start.address, 'notes': '',
    })

    cursor = vehicle.start
    sequence = 0
    visited_pickups = set()

    for stop in stops:
        distance_km, duration_min, via, shapes = provider.leg(cursor, stop)

        # --- driver hours: insert a statutory break before the leg if needed
        if options.auto_breaks and driving_since_break + duration_min > options.max_driving_minutes_before_break:
            clock += options.break_minutes
            totals['break_minutes'] += options.break_minutes
            driving_since_break = 0.0
            sequence += 1
            timeline.append({
                'sequence': sequence, 'type': 'break', 'name': 'Driver break (auto)',
                'lat': cursor.lat, 'lon': cursor.lon, 'location_id': None,
                'arrival': minutes_to_hhmm(clock - options.break_minutes),
                'departure': minutes_to_hhmm(clock),
                'load_kg': round(load_kg, 2), 'load_m3': round(load_m3, 3),
                'service_minutes': options.break_minutes,
                'order_id': None, 'order_ref': None, 'auto': True,
                'address': '', 'notes': f'{options.break_minutes} min break after '
                                        f'{options.max_driving_minutes_before_break} min driving',
            })

        load_ratio = (load_kg / vehicle.capacity_kg) if vehicle.capacity_kg else 0.0
        metrics = leg_metrics(distance_km, duration_min, profile, load_ratio)
        is_empty = load_kg <= 0.001

        legs.append({
            'from': cursor.name, 'from_lat': cursor.lat, 'from_lon': cursor.lon,
            'to': stop.name, 'to_lat': stop.lat, 'to_lon': stop.lon,
            'distance_km': round(distance_km, 2),
            'distance_miles': round(km_to_miles(distance_km), 2),
            'duration_min': round(duration_min, 1),
            'empty': is_empty,
            'load_kg': round(load_kg, 2),
            'co2_kg': metrics['co2_kg'],
            'cost_gbp': metrics['total_cost_gbp'],
            'via': via,
            'shapes': shapes,
        })

        totals['distance_km'] += distance_km
        totals['driving_minutes'] += duration_min
        totals['energy'] += metrics['energy']
        totals['co2_kg'] += metrics['co2_kg']
        totals['fuel_cost_gbp'] += metrics['fuel_cost_gbp']
        totals['running_cost_gbp'] += metrics['running_cost_gbp']
        totals['driver_cost_gbp'] += metrics['driver_cost_gbp']
        totals['empty_km' if is_empty else 'loaded_km'] += distance_km

        clock += duration_min
        driving_since_break += duration_min

        arrival = clock
        waiting = 0.0
        if stop.window_start is not None and arrival < stop.window_start:
            waiting = stop.window_start - arrival
            clock = float(stop.window_start)
        late_by = 0.0
        if stop.window_end is not None and clock > stop.window_end:
            late_by = clock - stop.window_end
            violations.append({
                'type': 'time_window', 'stop': stop.name, 'order_ref': stop.order_ref,
                'message': f'Arrives {int(late_by)} min after the {minutes_to_hhmm(stop.window_end)} window closes',
            })

        service_start = clock
        clock += stop.service_minutes
        totals['service_minutes'] += stop.service_minutes
        totals['waiting_minutes'] += waiting
        if stop.type in ('rest', 'break'):
            driving_since_break = 0.0

        # --- load changes
        if stop.type == 'pickup':
            load_kg += stop.weight_kg
            load_m3 += stop.volume_m3
            load_pallets += stop.pallets
            visited_pickups.add(stop.order_id)
        elif stop.type == 'delivery':
            load_kg += stop.weight_kg          # weight_kg is negative for deliveries
            load_m3 += stop.volume_m3
            load_pallets += stop.pallets

        load_kg = 0.0 if abs(load_kg) < 1e-6 else load_kg
        load_m3 = 0.0 if abs(load_m3) < 1e-9 else load_m3
        peak_load_kg = max(peak_load_kg, load_kg)
        peak_load_m3 = max(peak_load_m3, load_m3)

        if options.enforce_capacity and _over_capacity(vehicle, load_kg, load_m3, load_pallets):
            return _infeasible(
                vehicle,
                f'Capacity exceeded at {stop.name} '
                f'({load_kg:.0f} kg / {load_m3:.1f} m³ vs {vehicle.capacity_kg:.0f} kg / {vehicle.capacity_m3:.1f} m³)'
            )

        sequence += 1
        timeline.append({
            'sequence': sequence, 'type': stop.type, 'name': stop.name,
            'lat': stop.lat, 'lon': stop.lon, 'location_id': stop.location_id,
            'arrival': minutes_to_hhmm(arrival),
            'service_start': minutes_to_hhmm(service_start),
            'departure': minutes_to_hhmm(clock),
            'waiting_minutes': round(waiting, 1),
            'late_minutes': round(late_by, 1),
            'load_kg': round(load_kg, 2), 'load_m3': round(load_m3, 3),
            'service_minutes': round(stop.service_minutes, 1),
            'order_id': stop.order_id, 'order_ref': stop.order_ref,
            'window_start': minutes_to_hhmm(stop.window_start),
            'window_end': minutes_to_hhmm(stop.window_end),
            'packages': stop.packages,
            'address': stop.address, 'notes': stop.notes, 'contact': stop.contact,
            'auto': stop.auto, 'key': stop.key,
        })
        cursor = stop

    # --- return leg
    end_stop = vehicle.end if vehicle.end else (vehicle.start if options.return_to_start and vehicle.return_to_start else None)
    if end_stop is not None and stops:
        distance_km, duration_min, via, shapes = provider.leg(cursor, end_stop)
        load_ratio = (load_kg / vehicle.capacity_kg) if vehicle.capacity_kg else 0.0
        metrics = leg_metrics(distance_km, duration_min, profile, load_ratio)
        is_empty = load_kg <= 0.001
        legs.append({
            'from': cursor.name, 'from_lat': cursor.lat, 'from_lon': cursor.lon,
            'to': end_stop.name, 'to_lat': end_stop.lat, 'to_lon': end_stop.lon,
            'distance_km': round(distance_km, 2),
            'distance_miles': round(km_to_miles(distance_km), 2),
            'duration_min': round(duration_min, 1),
            'empty': is_empty, 'load_kg': round(load_kg, 2),
            'co2_kg': metrics['co2_kg'], 'cost_gbp': metrics['total_cost_gbp'],
            'via': via, 'shapes': shapes, 'return_leg': True,
        })
        totals['distance_km'] += distance_km
        totals['driving_minutes'] += duration_min
        totals['energy'] += metrics['energy']
        totals['co2_kg'] += metrics['co2_kg']
        totals['fuel_cost_gbp'] += metrics['fuel_cost_gbp']
        totals['running_cost_gbp'] += metrics['running_cost_gbp']
        totals['driver_cost_gbp'] += metrics['driver_cost_gbp']
        totals['empty_km' if is_empty else 'loaded_km'] += distance_km
        clock += duration_min
        sequence += 1
        timeline.append({
            'sequence': sequence, 'type': 'depot_end', 'name': end_stop.name,
            'lat': end_stop.lat, 'lon': end_stop.lon, 'location_id': end_stop.location_id,
            'arrival': minutes_to_hhmm(clock), 'departure': minutes_to_hhmm(clock),
            'load_kg': round(load_kg, 2), 'load_m3': round(load_m3, 3),
            'service_minutes': 0, 'order_id': None, 'order_ref': None, 'auto': False,
            'address': end_stop.address, 'notes': '',
        })

    total_minutes = clock - vehicle.shift_start_min
    if vehicle.max_shift_minutes and total_minutes > vehicle.max_shift_minutes:
        violations.append({
            'type': 'shift_length', 'stop': None, 'order_ref': None,
            'message': f'Route takes {total_minutes / 60:.1f} h, over the '
                       f'{vehicle.max_shift_minutes / 60:.1f} h shift limit',
        })
        if options.enforce_shift:
            return _infeasible(vehicle, 'Route exceeds the maximum shift length')

    # The repositioning distance from base to the first revenue stop.
    initial_empty_km = legs[0]['distance_km'] if legs and legs[0]['empty'] else 0.0

    distance_km = totals['distance_km']
    utilisation_kg = (peak_load_kg / vehicle.capacity_kg * 100) if vehicle.capacity_kg else 0.0
    utilisation_m3 = (peak_load_m3 / vehicle.capacity_m3 * 100) if vehicle.capacity_m3 else 0.0
    total_cost = totals['fuel_cost_gbp'] + totals['running_cost_gbp'] + totals['driver_cost_gbp']

    return {
        'feasible': True,
        'vehicle_id': vehicle.id,
        'vehicle_name': vehicle.name,
        'vehicle_type': vehicle.type,
        'registration': vehicle.registration,
        'driver_id': vehicle.driver_id,
        'driver_name': vehicle.driver_name,
        'stops': [s.to_dict() for s in stops],
        'timeline': timeline,
        'legs': legs,
        'violations': violations,
        'metrics': {
            'stop_count': len([s for s in stops if s.type in ('pickup', 'delivery')]),
            'total_stops': len(stops),
            'total_distance_km': round(distance_km, 2),
            'total_distance_miles': round(km_to_miles(distance_km), 2),
            'loaded_km': round(totals['loaded_km'], 2),
            'empty_km': round(totals['empty_km'], 2),
            'empty_miles': round(km_to_miles(totals['empty_km']), 2),
            'empty_pct': round((totals['empty_km'] / distance_km * 100) if distance_km else 0.0, 1),
            'initial_empty_km': round(initial_empty_km, 2),
            'initial_empty_miles': round(km_to_miles(initial_empty_km), 2),
            'driving_minutes': round(totals['driving_minutes']),
            'service_minutes': round(totals['service_minutes']),
            'waiting_minutes': round(totals['waiting_minutes']),
            'break_minutes': round(totals['break_minutes']),
            'total_minutes': round(total_minutes),
            'start_time': minutes_to_hhmm(vehicle.shift_start_min),
            'end_time': minutes_to_hhmm(clock),
            'energy': round(totals['energy'], 2),
            'energy_unit': 'kWh' if (vehicle.fuel_type or '').lower() == 'electric' else 'L',
            'estimated_fuel_l': round(totals['energy'], 2),
            'co2_kg': round(totals['co2_kg'], 2),
            'fuel_cost_gbp': round(totals['fuel_cost_gbp'], 2),
            'running_cost_gbp': round(totals['running_cost_gbp'], 2),
            'driver_cost_gbp': round(totals['driver_cost_gbp'], 2),
            'estimated_cost_gbp': round(total_cost, 2),
            'cost_per_km': round(total_cost / distance_km, 2) if distance_km else 0.0,
            'start_load_kg': round(start_load_kg, 2),
            'peak_load_kg': round(peak_load_kg, 2),
            'peak_load_m3': round(peak_load_m3, 3),
            'capacity_kg': vehicle.capacity_kg,
            'capacity_m3': vehicle.capacity_m3,
            'weight_utilisation_pct': round(min(utilisation_kg, 999), 1),
            'volume_utilisation_pct': round(min(utilisation_m3, 999), 1),
        },
    }


def _has_matching_pickup(stops: List[Stop], delivery: Stop) -> bool:
    return any(s.type == 'pickup' and s.order_id and s.order_id == delivery.order_id for s in stops)


def _over_capacity(vehicle: Vehicle, load_kg, load_m3, pallets) -> bool:
    if vehicle.capacity_kg and load_kg - vehicle.capacity_kg > 1e-6:
        return True
    if vehicle.capacity_m3 and load_m3 - vehicle.capacity_m3 > 1e-6:
        return True
    if vehicle.max_pallets and pallets > vehicle.max_pallets:
        return True
    return False


def _infeasible(vehicle: Vehicle, reason: str) -> dict:
    return {'feasible': False, 'vehicle_id': vehicle.id, 'vehicle_name': vehicle.name, 'reason': reason}


# --------------------------------------------------------------------------
# Objective
# --------------------------------------------------------------------------

def route_objective(result: dict, preference: str) -> float:
    """Scalar score for a costed route — lower is better."""
    if not result.get('feasible'):
        return float('inf')
    m = result['metrics']
    late = sum(1 for v in result.get('violations', []) if v['type'] == 'time_window')
    penalty = late * 50.0
    if preference == 'fastest':
        return m['total_minutes'] + m['empty_km'] * 0.2 + penalty
    if preference == 'cheapest':
        return m['estimated_cost_gbp'] + m['empty_km'] * 0.1 + penalty
    # greenest (default): CO2 first, with empty running penalised hard
    return m['co2_kg'] * 3.0 + m['empty_km'] * 0.5 + m['total_distance_km'] * 0.1 + penalty


