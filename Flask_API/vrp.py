@dataclass
class Stop:
    key: str
    type: str                      # pickup | delivery | rest | break | fuel | custom
    name: str
    lat: float
    lon: float
    service_minutes: float = 0.0
    order_id: Optional[str] = None
    order_ref: Optional[str] = None
    location_id: Optional[str] = None
    weight_kg: float = 0.0         # signed: + on pickup, - on delivery
    volume_m3: float = 0.0
    pallets: int = 0
    window_start: Optional[int] = None   # minutes from midnight
    window_end: Optional[int] = None
    address: str = ''
    notes: str = ''
    contact: str = ''
    packages: List[dict] = field(default_factory=list)
    vehicle_id: Optional[str] = None     # pre-assignment / lock
    auto: bool = False                   # generated by the engine (driver breaks)
    sequence: int = 0                    # position in the request (locked mode)

    def to_dict(self):
        return {
            'key': self.key,
            'type': self.type,
            'name': self.name,
            'lat': self.lat,
            'lon': self.lon,
            'service_minutes': round(self.service_minutes, 1),
            'order_id': self.order_id,
            'order_ref': self.order_ref,
            'location_id': self.location_id,
            'weight_kg': round(self.weight_kg, 2),
            'volume_m3': round(self.volume_m3, 3),
            'pallets': self.pallets,
            'window_start': minutes_to_hhmm(self.window_start),
            'window_end': minutes_to_hhmm(self.window_end),
            'address': self.address,
            'notes': self.notes,
            'contact': self.contact,
            'packages': self.packages,
            'auto': self.auto,
        }


def stop_from_dict(data: dict) -> 'Stop':
    """Rebuild a Stop from its serialised form (used when re-costing a saved plan)."""
    return Stop(
        key=data.get('key') or f"stop-{data.get('name', '')}",
        type=data.get('type', 'custom'),
        name=data.get('name', 'Stop'),
        lat=float(data['lat']), lon=float(data['lon']),
        service_minutes=float(data.get('service_minutes') or 0),
        order_id=data.get('order_id'),
        order_ref=data.get('order_ref'),
        location_id=data.get('location_id'),
        weight_kg=float(data.get('weight_kg') or 0),
        volume_m3=float(data.get('volume_m3') or 0),
        pallets=int(data.get('pallets') or 0),
        window_start=hhmm_to_minutes(data.get('window_start')),
        window_end=hhmm_to_minutes(data.get('window_end')),
        address=data.get('address', ''),
        notes=data.get('notes', ''),
        contact=data.get('contact', ''),
        packages=data.get('packages') or [],
        auto=bool(data.get('auto')),
    )


@dataclass
class Job:
    """One order: a pickup, a delivery, or both.

    * pickup + delivery — a normal collection-and-delivery job;
    * delivery only     — goods loaded at the depot before departure;
    * pickup only       — a collection brought back to base.
    """
    order_id: str
    reference: str
    delivery: Optional[Stop] = None
    pickup: Optional[Stop] = None
    weight_kg: float = 0.0
    volume_m3: float = 0.0
    pallets: int = 0
    priority: int = 3               # 1 = highest
    temperature_controlled: bool = False
    hazardous: bool = False
    vehicle_id: Optional[str] = None  # hard assignment when set

    @property
    def stops(self) -> List[Stop]:
        return [s for s in (self.pickup, self.delivery) if s is not None]


@dataclass
class Vehicle:
    id: str
    name: str
    start: Stop
    end: Optional[Stop] = None
    registration: str = ''
    type: str = 'van'
    capacity_kg: float = 1000.0
    capacity_m3: float = 10.0
    max_pallets: int = 0
    fuel_type: str = 'diesel'
    fuel_efficiency_km_per_l: float = 3.5
    kwh_per_km: float = 0.0
