"""Multi-vehicle, multi-order route planning engine.

Pure standard-library so it can be unit-tested without Flask/Mongo/Torch.

What it supports
----------------
* many pickups and many drop-offs per vehicle, with pickup-before-delivery
  precedence kept valid at every step;
* orders that are simply loaded at the depot (delivery-only) as well as true
  pickup->delivery jobs;
* custom stops (rest, break, fuel, arbitrary waypoints) with their own service
  time, plus automatic driving-hours breaks;
* weight / volume / pallet capacity per vehicle;
* time windows (arrive early -> wait, arrive late -> flagged);
* empty-running measurement, including the repositioning leg from a vehicle's
  start location to its first pickup;
* a locked sequence mode so a planner can hand-order the stops and still get
  costed, validated output.

The optimiser is a cheapest-insertion construction followed by or-opt / 2-opt
local search. That is the standard practical approach for pickup-and-delivery
problems of this size and it keeps the runtime well inside a web request.
"""
import time
from dataclasses import dataclass, field, replace
from typing import Callable, Dict, List, Optional, Tuple

from config import Config
from geo import km_to_miles, leg_metrics, road_distance_km, travel_minutes

