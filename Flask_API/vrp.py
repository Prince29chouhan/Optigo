# Construction + local search
# --------------------------------------------------------------------------

def _precedence_ok(stops: List[Stop]) -> bool:
    seen_pickup = set()
    for stop in stops:
        if stop.type == 'pickup' and stop.order_id:
            seen_pickup.add(stop.order_id)
        elif stop.type == 'delivery' and stop.order_id:
            has_pickup = any(s.type == 'pickup' and s.order_id == stop.order_id for s in stops)
            if has_pickup and stop.order_id not in seen_pickup:
                return False
    return True


def _precedence_pairs(stops: List[Stop]) -> List[Tuple[int, int]]:
    """(pickup_index, delivery_index) for every order present in the route."""
    pickups, deliveries = {}, {}
    for index, stop in enumerate(stops):
        if not stop.order_id:
            continue
        if stop.type == 'pickup':
            pickups[stop.order_id] = index
        elif stop.type == 'delivery':
            deliveries[stop.order_id] = index
    return [(pickups[order], deliveries[order]) for order in pickups if order in deliveries]


def _relocate_ok(stops: List[Stop], source: int, target: int) -> bool:
    """Would moving stops[source] to position `target` keep pickup before drop?"""
    stop = stops[source]
    if stop.type not in ('pickup', 'delivery') or not stop.order_id:
        return True
    wanted = 'delivery' if stop.type == 'pickup' else 'pickup'
    partner = next((i for i, s in enumerate(stops)
                    if s.order_id == stop.order_id and s.type == wanted), None)
    if partner is None:
        return True
    partner_after = partner if partner < source else partner - 1
    return target < partner_after if stop.type == 'pickup' else target > partner_after


def _reversal_ok(pairs: List[Tuple[int, int]], start: int, end: int) -> bool:
    """A 2-opt reversal is only valid if it does not flip a pickup/delivery pair."""
    return not any(start <= pickup < end and start <= delivery < end for pickup, delivery in pairs)


def _end_node(vehicle: Vehicle, options: PlanOptions) -> Optional[Stop]:
    if vehicle.end:
        return vehicle.end
    return vehicle.start if options.return_to_start and vehicle.return_to_start else None


def _insertion_deltas(vehicle: Vehicle, stops: List[Stop], stop: Stop,
                      provider: DistanceProvider, options: PlanOptions,
                      first_index: int = 0) -> List[Tuple[float, int]]:
    """Extra distance for inserting `stop` at each position — O(1) per position.

    Full route evaluation is far too expensive to run for every candidate
    position (it builds a whole timeline); this cheap detour cost is used to
    shortlist positions, and only the shortlist is evaluated properly.
    """
    end = _end_node(vehicle, options)
    nodes = [vehicle.start] + stops
    deltas = []
    for index in range(first_index, len(stops) + 1):
        previous = nodes[index]
        following = stops[index] if index < len(stops) else end
        if following is None:                       # appending with no return leg
            delta = provider.leg(previous, stop)[0]
        else:
            delta = (provider.leg(previous, stop)[0] + provider.leg(stop, following)[0]
                     - provider.leg(previous, following)[0])
        deltas.append((delta, index))
    deltas.sort(key=lambda item: item[0])
    return deltas


def _candidate_routes(vehicle: Vehicle, stops: List[Stop], job: Job,
                      provider: DistanceProvider, options: PlanOptions) -> List[List[Stop]]:
    """Shortlist of candidate stop sequences for adding `job` to a route."""
    width = max(1, options.insertion_width)

    if job.pickup is None or job.delivery is None:
        stop = job.delivery or job.pickup
        return [
            stops[:index] + [stop] + stops[index:]
            for _, index in _insertion_deltas(vehicle, stops, stop, provider, options)[:width * 2]
        ]

    candidates = []
    for _, pickup_index in _insertion_deltas(vehicle, stops, job.pickup, provider, options)[:width]:
        with_pickup = stops[:pickup_index] + [job.pickup] + stops[pickup_index:]
        for _, delivery_index in _insertion_deltas(
                vehicle, with_pickup, job.delivery, provider, options,
                first_index=pickup_index + 1)[:width]:
            candidates.append(
                with_pickup[:delivery_index] + [job.delivery] + with_pickup[delivery_index:])
    return candidates


def plan(vehicles: List[Vehicle], jobs: List[Job], extra_stops: List[Stop],
         options: PlanOptions, provider: Optional[DistanceProvider] = None) -> dict:
    """Assign jobs to vehicles and sequence each vehicle's stops."""
    provider = provider or DistanceProvider(options.road_factor)
    if not vehicles:
        return {'vehicles': [], 'unassigned': [
            {'order_id': j.order_id, 'reference': j.reference, 'reason': 'No vehicle available'} for j in jobs
        ], 'summary': _summarise([], jobs)}

    routes: Dict[str, List[Stop]] = {v.id: [] for v in vehicles}
    vehicles_by_id = {v.id: v for v in vehicles}
    unassigned: List[dict] = []

    # Locked mode: visit the stops exactly in the order they were given.
    if not options.optimize_sequence:
        return _plan_locked(vehicles, jobs, extra_stops, options, provider)

    # Physical custom stops (rest/fuel/waypoints) are placed first so the
    # optimiser routes deliveries around them.
    for stop in extra_stops:
        target = stop.vehicle_id if stop.vehicle_id in routes else vehicles[0].id
        routes[target].append(stop)

    deadline = time.monotonic() + max(1.0, options.time_budget_seconds)

    # --- construction: hardest jobs first, cheapest feasible insertion
    ordered_jobs = sorted(jobs, key=lambda j: (j.priority, -j.weight_kg, -j.volume_m3))
    for job in ordered_jobs:
        best = None
        candidate_vehicles = (
            [vehicles_by_id[job.vehicle_id]] if job.vehicle_id in vehicles_by_id else vehicles
        )
        for vehicle in candidate_vehicles:
            if job.temperature_controlled and not vehicle.temperature_controlled:
                continue
            current = routes[vehicle.id]
            base_score = (route_objective(evaluate_route(vehicle, current, provider, options),
                                          options.preference) if current else 0.0)
            for candidate in _candidate_routes(vehicle, current, job, provider, options):
                if not _precedence_ok(candidate):
                    continue
                result = evaluate_route(vehicle, candidate, provider, options)
                if not result.get('feasible'):
                    continue
                score = route_objective(result, options.preference) - base_score
                if best is None or score < best[0]:
                    best = (score, vehicle.id, candidate)
        if best is None:
            reason = 'No vehicle has the capacity (or equipment) for this order'
            if job.temperature_controlled:
                reason = 'No temperature-controlled vehicle available with spare capacity'
            unassigned.append({'order_id': job.order_id, 'reference': job.reference, 'reason': reason})
        else:
            routes[best[1]] = best[2]

    # --- improvement (best-effort within the remaining time budget)
    for vehicle in vehicles:
        routes[vehicle.id] = _local_search(vehicle, routes[vehicle.id], provider, options, deadline)

    results = []
    for vehicle in vehicles:
        stops = routes[vehicle.id]
        if not stops:
            continue
        result = evaluate_route(vehicle, stops, provider, options)
        if result.get('feasible'):
            results.append(result)
        else:
            for stop in stops:
                if stop.order_id:
                    unassigned.append({'order_id': stop.order_id, 'reference': stop.order_ref,
                                       'reason': result.get('reason', 'Route infeasible')})

    return {'vehicles': results, 'unassigned': unassigned, 'summary': _summarise(results, jobs, unassigned)}


def _plan_locked(vehicles: List[Vehicle], jobs: List[Job], extra_stops: List[Stop],
                 options: PlanOptions, provider: DistanceProvider) -> dict:
    """Plan without re-ordering: stops are visited in the order they arrived.

    Stops are grouped by their `vehicle_id` when one is set, otherwise they all
    ride on the first vehicle — with a locked sequence there is nothing for the
    optimiser to split across a fleet.
    """
    all_stops = [stop for job in jobs for stop in job.stops] + list(extra_stops)
    all_stops.sort(key=lambda stop: stop.sequence)

    routes: Dict[str, List[Stop]] = {vehicle.id: [] for vehicle in vehicles}
    for stop in all_stops:
        target = stop.vehicle_id if stop.vehicle_id in routes else vehicles[0].id
        routes[target].append(stop)

    results, unassigned = [], []
    for vehicle in vehicles:
        stops = routes[vehicle.id]
        if not stops:
            continue
        # Capacity is reported as a violation here rather than dropping work:
        # the planner asked for this exact sequence and needs to see why it fails.
        relaxed = replace(options, enforce_capacity=False)
        result = evaluate_route(vehicle, stops, provider, relaxed)
        if not result.get('feasible'):
            unassigned.extend({'order_id': stop.order_id, 'reference': stop.order_ref,
                               'reason': result.get('reason', 'Sequence not feasible')}
                              for stop in stops if stop.order_id)
            continue
        strict = evaluate_route(vehicle, stops, provider, options)
        if not strict.get('feasible'):
            result.setdefault('violations', []).append({
                'type': 'capacity', 'stop': None, 'order_ref': None,
                'message': strict.get('reason', 'Load exceeds the vehicle capacity'),
            })
        if not _precedence_ok(stops):
            result.setdefault('violations', []).append({
                'type': 'precedence', 'stop': None, 'order_ref': None,
                'message': 'A delivery is sequenced before its pickup',
            })
        results.append(result)

    return {'vehicles': results, 'unassigned': unassigned,
            'summary': _summarise(results, jobs, unassigned)}


def _route_distance(vehicle: Vehicle, stops: List[Stop], provider: DistanceProvider,
                    options: PlanOptions) -> float:
    """Total driving distance of a sequence — the cheap proxy used for pruning."""
    if not stops:
        return 0.0
    total = 0.0
    cursor = vehicle.start
    for stop in stops:
        total += provider.leg(cursor, stop)[0]
        cursor = stop
    end = _end_node(vehicle, options)
    if end is not None:
        total += provider.leg(cursor, end)[0]
    return total


def _local_search(vehicle: Vehicle, stops: List[Stop], provider: DistanceProvider,
                  options: PlanOptions, deadline: Optional[float] = None) -> List[Stop]:
    """Or-opt (relocate) + 2-opt passes, precedence-safe.

    Candidate moves are ranked by their distance delta (cheap) and only the most
    promising ones are scored with a full route evaluation (expensive). Without
    that split a 40-order plan takes minutes; with it, seconds.
    """
    if len(stops) < 3:
        return stops

    best = stops
    best_score = route_objective(evaluate_route(vehicle, best, provider, options), options.preference)
    verify_budget = max(4, options.verify_per_pass)

    for _ in range(max(1, options.local_search_rounds)):
        if deadline and time.monotonic() > deadline:
            break

        base_distance = _route_distance(vehicle, best, provider, options)
        pairs = _precedence_pairs(best)
        moves = []

        # relocate one stop elsewhere in the route
        for i in range(len(best)):
            without = best[:i] + best[i + 1:]
            without_distance = _route_distance(vehicle, without, provider, options)
            for delta, j in _insertion_deltas(vehicle, without, best[i], provider, options):
                if j == i or without_distance + delta >= base_distance - 1e-6:
                    continue
                # Precedence is checked here, before ranking: the shortest moves
                # are usually the invalid ones (a drop pulled ahead of its
                # pickup), and ranking them would crowd out every valid move.
                if not _relocate_ok(best, i, j):
                    continue
                moves.append((without_distance + delta, without[:j] + [best[i]] + without[j:]))

        # 2-opt: reverse a segment
        for i in range(len(best) - 1):
            for j in range(i + 2, len(best) + 1):
                if not _reversal_ok(pairs, i, j):
                    continue
                candidate = best[:i] + list(reversed(best[i:j])) + best[j:]
                candidate_distance = _route_distance(vehicle, candidate, provider, options)
                if candidate_distance < base_distance - 1e-6:
                    moves.append((candidate_distance, candidate))

        moves.sort(key=lambda move: move[0])
        improved = False
        for _, candidate in moves[:verify_budget]:
            if deadline and time.monotonic() > deadline:
                break
            if not _precedence_ok(candidate):
                continue
            result = evaluate_route(vehicle, candidate, provider, options)
            score = route_objective(result, options.preference)
            if score < best_score - 1e-6:
                best, best_score, improved = candidate, score, True
                break     # restart the pass from the improved route

        if not improved:
            break
    return best


def _summarise(results: List[dict], jobs: List[Job], unassigned: Optional[List[dict]] = None) -> dict:
    unassigned = unassigned or []
    totals = {
        'vehicles_used': len(results),
        'orders_planned': len(jobs) - len(unassigned),
        'orders_unassigned': len(unassigned),
        'total_stops': sum(r['metrics']['total_stops'] for r in results),
        'total_distance_km': round(sum(r['metrics']['total_distance_km'] for r in results), 2),
        'total_distance_miles': round(sum(r['metrics']['total_distance_miles'] for r in results), 2),
        'empty_km': round(sum(r['metrics']['empty_km'] for r in results), 2),
        'empty_miles': round(sum(r['metrics']['empty_miles'] for r in results), 2),
        'loaded_km': round(sum(r['metrics']['loaded_km'] for r in results), 2),
        'total_minutes': round(sum(r['metrics']['total_minutes'] for r in results)),
        'driving_minutes': round(sum(r['metrics']['driving_minutes'] for r in results)),
        'co2_kg': round(sum(r['metrics']['co2_kg'] for r in results), 2),
        'estimated_fuel_l': round(sum(r['metrics']['estimated_fuel_l'] for r in results), 2),
        'estimated_cost_gbp': round(sum(r['metrics']['estimated_cost_gbp'] for r in results), 2),
        'violations': sum(len(r.get('violations', [])) for r in results),
    }
    total = totals['total_distance_km']
    totals['empty_pct'] = round((totals['empty_km'] / total * 100) if total else 0.0, 1)
    if results:
        totals['avg_weight_utilisation_pct'] = round(
            sum(r['metrics']['weight_utilisation_pct'] for r in results) / len(results), 1)
        totals['avg_volume_utilisation_pct'] = round(
            sum(r['metrics']['volume_utilisation_pct'] for r in results) / len(results), 1)
    else:
        totals['avg_weight_utilisation_pct'] = 0.0
        totals['avg_volume_utilisation_pct'] = 0.0
    return totals


def plan_fixed_sequence(vehicle: Vehicle, stops: List[Stop], options: PlanOptions,
                        provider: Optional[DistanceProvider] = None) -> dict:
    """Cost a hand-ordered sequence (used by the drag-to-reorder planner UI)."""
    provider = provider or DistanceProvider(options.road_factor)
    result = evaluate_route(vehicle, stops, provider, options)
    if result.get('feasible') and not _precedence_ok(stops):
        result.setdefault('violations', []).append({
            'type': 'precedence', 'stop': None, 'order_ref': None,
            'message': 'A delivery is sequenced before its pickup',
        })
    return result
