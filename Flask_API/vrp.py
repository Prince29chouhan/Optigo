def hhmm_to_minutes(value) -> Optional[int]:
    """'08:30' / 510 / '510' -> 510. Returns None when unparseable."""
    if value is None or value == '':
        return None
    if isinstance(value, (int, float)):
        return int(value)
    text = str(value).strip()
    days = 0
    if '(+' in text:   # "01:00 (+1d)" — produced by minutes_to_hhmm for next-day times
        head, _, tail = text.partition('(+')
        text = head.strip()
        digits = ''.join(c for c in tail if c.isdigit())
        days = int(digits) if digits else 0
    if ':' in text:
        try:
            hours, minutes = text.split(':')[:2]
            return days * 1440 + int(hours) * 60 + int(minutes)
        except ValueError:
            return None
    try:
        return int(float(text))
    except ValueError:
        return None


def minutes_to_hhmm(value) -> Optional[str]:
    if value is None:
        return None
    value = int(round(value))
    days, rem = divmod(value, 1440)
    text = f'{rem // 60:02d}:{rem % 60:02d}'
    return f'{text} (+{days}d)' if days else text


class DistanceProvider:
    """Caches leg distances/durations, optionally via a network corridor.

    `corridor_fn(a, b)` may return `(distance_km, duration_min, via_points)` or
    `(distance_km, duration_min, via_points, shapes)` for pairs the trained road
    graph knows about; anything else falls back to the great-circle estimate
    inflated by the road factor.

    `shapes` are encoded road polylines, one per hop of the corridor, so the map
    can draw the real road rather than a straight line.
    """

    def __init__(self, road_factor=None, speed_kmh=None, corridor_fn: Optional[Callable] = None):
        self.road_factor = road_factor or Config.ROAD_FACTOR
        self.speed_kmh = speed_kmh or Config.DEFAULT_SPEED_KMH
        self.corridor_fn = corridor_fn
        self._cache: Dict[Tuple, Tuple[float, float, list, list]] = {}

    def leg(self, a: Stop, b: Stop) -> Tuple[float, float, list, list]:
        key = (round(a.lat, 5), round(a.lon, 5), round(b.lat, 5), round(b.lon, 5))
        cached = self._cache.get(key)
        if cached:
            return cached

        result = None
        if self.corridor_fn is not None:
            try:
                result = self.corridor_fn(a, b)
            except Exception:  # noqa: BLE001 - corridor is an optimisation, never fatal
                result = None
        if not result:
            distance = road_distance_km(a.lat, a.lon, b.lat, b.lon, self.road_factor)
            result = (distance, travel_minutes(distance, self.speed_kmh), [], [])

        distance, duration, via = result[0], result[1], result[2]
        shapes = result[3] if len(result) > 3 else []
        value = (float(distance), float(duration), list(via or []), list(shapes or []))
        self._cache[key] = value
        return value


